"""
Load the benchmark's trip templates and disruption catalogue and expand them
into concrete scenarios (trip × disruption kind × severity).

    python eval/generate_scenarios.py   → writes eval/scenarios/scenarios.yaml
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path
from typing import Any

import yaml

EVAL_DIR = Path(__file__).resolve().parent
SCENARIO_DIR = EVAL_DIR / "scenarios"
RESULTS_DIR = EVAL_DIR / "results"
RESULTS_V2_DIR = EVAL_DIR / "results_v2"      # evaluation metrics v2; never overwrites RESULTS_DIR
BACKEND_DIR = EVAL_DIR.parent / "backend"


def use_backend() -> None:
    """Make ``app`` importable and force mock mode (the benchmark never uses keys or the network)."""
    import os

    os.environ["VOYAGESYNC_MODE"] = "mock"
    os.environ["VOYAGESYNC_LLM_API_KEY"] = ""
    if str(BACKEND_DIR) not in sys.path:
        sys.path.insert(0, str(BACKEND_DIR))


def _load(name: str) -> Any:
    with open(SCENARIO_DIR / name, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def load_trips() -> dict[str, dict[str, Any]]:
    return {t["id"]: t for t in _load("trips.yaml")}


def load_disruptions() -> list[dict[str, Any]]:
    return _load("disruptions.yaml")


def nights(goal: dict[str, Any]) -> int:
    return (date.fromisoformat(str(goal["return_date"])) - date.fromisoformat(str(goal["departure_date"]))).days


def _target(target: str, goal: dict[str, Any]) -> str:
    n = nights(goal)
    if target == "storm_mid":
        return f"weather_day_{max(1, (n + 1) // 2)}"
    if target == "storm_last":
        return f"weather_day_{n}"
    return target


def _suffix(facts: dict[str, Any]) -> str:
    value = facts.get("delay_minutes", facts.get("pct"))
    return f"_{value}" if value is not None else ""


def expand() -> list[dict[str, Any]]:
    """Every trip × every disruption level, in a stable order."""
    scenarios = []
    for trip_id, trip in load_trips().items():
        for spec in load_disruptions():
            for level in spec["levels"]:
                facts = dict(level.get("facts") or {})
                scenarios.append({
                    "id": f"{trip_id}__{spec['kind']}{_suffix(facts)}",
                    "trip": trip_id,
                    "kind": spec["kind"],
                    "severity": level["severity"],
                    "type": spec["type"],
                    "target": _target(spec["target"], trip["goal"]),
                    "facts": facts,
                })
    return scenarios


def load_scenarios() -> list[dict[str, Any]]:
    return _load("scenarios.yaml")["scenarios"]


def write_scenarios() -> Path:
    scenarios = expand()
    path = SCENARIO_DIR / "scenarios.yaml"
    header = ("# Generated by eval/generate_scenarios.py from trips.yaml × disruptions.yaml. Do not edit by hand.\n")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header)
        yaml.safe_dump({"count": len(scenarios), "scenarios": scenarios}, fh, sort_keys=False, allow_unicode=True,
                       width=120)
    return path
